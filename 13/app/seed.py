#: Залы кинотеатра.
_HALLS = ["Зал 1", "Зал 2", "IMAX", "VIP"]


def _make_sessions(index: int, status: str) -> list[Session]:
    """Сгенерировать расписание сеансов для фильма."""
    if status == "archived":
        return []
    formats = ["2D", "3D", "IMAX"]
    sessions: list[Session] = []
    for slot, hour in enumerate(("10:30", "14:00", "18:30")):
        sessions.append(
            Session(
                date="2024-06-01",
                time=hour,
                hall=_HALLS[(index + slot) % len(_HALLS)],
                price=350.0 + 50.0 * slot,
                format=formats[(index + slot) % len(formats)],
            )
        )
    return sessions


def build_movies() -> list[Movie]:
    """Собрать список моделей Movie из сырых данных."""
    movies: list[Movie] = []
    for index, row in enumerate(_RAW):
        title, director, country, year, genres, actors, duration, rating, status = row
        movies.append(
            Movie(
                title=title,
                director=Director(name=director, country=country),
                year=year,
                genres=list(genres),
                actors=list(actors),
                duration=duration,
                rating=rating,
                poster=f"https://posters.local/cinema/{index + 1}.jpg",
                sessions=_make_sessions(index, status),
                status=status,
            )
        )
    return movies


def seed(movies_list: list[Movie], repository) -> int:
    """Заполнить репозиторий начальными данными, если он пуст."""
    if repository.count({}) > 0:
        return 0
    for movie in movies_list:
        repository.create(movie)
    return len(movies_list)
